  const phraseKeys = Object.keys(entries)
    .filter((key) => key.includes(' '))
    .sort((a, b) => b.split(/\s+/).length - a.split(/\s+/).length);

  function normalize(value) {
    return String(value || '')
      .replace(/[’‘]/g, "'")
      .replace(/[，。？！,.!?;:“”"]/g, ' ')
      .replace(/\s+/g, ' ')
      .trim()
      .toLowerCase();
  }

  function dynamicEntry(key) {
    if (/^\d{1,2}\s+\d{2}$/.test(key)) {
      return { type: 'word', zh: '时间：' + key.replace(/\s+/, ':'), note: '当前语境中的钟点。' };
    }
    if (/^\d+$/.test(key)) {
      return { type: 'word', zh: '数字：' + key, note: '具体含义由当前场景决定。' };
    }
    return null;
  }

  function segment(text) {
    const source = String(text || '');
    const wordPattern = /\b(?:a\.m\.|p\.m\.)|[A-Za-z]+(?:[’'][A-Za-z]+)*(?:-[A-Za-z0-9]+)?|\d+(?::\d+)?|\d+-\d+/gi;
    const words = [];
    let match;
    while ((match = wordPattern.exec(source))) {
      words.push({ text: match[0], start: match.index, end: wordPattern.lastIndex, normalized: normalize(match[0]) });
    }
    const output = [];
    let cursor = 0;
    let index = 0;
    while (index < words.length) {
      let found = null;
      for (let count = Math.min(5, words.length - index); count >= 1; count--) {
        let gapOK = true;
        for (let offset = 1; offset < count; offset++) {
          const gap = source.slice(words[index + offset - 1].end, words[index + offset].start);
          if (!/^\s*$/.test(gap)) gapOK = false;
        }
        if (!gapOK) continue;
        const key = words.slice(index, index + count).map((word) => word.normalized).join(' ');
        if (phraseKeys.includes(key) || (count === 1 && entries[key])) {
          found = { key, count };
          break;
        }
      }
      if (!found) {
        found = { key: words[index].normalized, count: 1 };
      }
      const first = words[index];
      const last = words[index + found.count - 1];
      if (first.start > cursor) output.push({ kind: 'text', text: source.slice(cursor, first.start) });
      const entry = entries[found.key] || dynamicEntry(found.key);
      output.push({
        kind: entry && entry.type === 'phrase' ? 'phrase' : 'word',
        term: found.key,
        text: source.slice(first.start, last.end),
        zh: entry ? entry.zh : '暂无词义记录',
        note: entry ? entry.note || '' : '这个词还没有收录释义。'
      });
      cursor = last.end;
      index += found.count;
    }
    if (cursor < source.length) output.push({ kind: 'text', text: source.slice(cursor) });
    return output;
  }

  function lookup(term) {
    const key = normalize(term);
    const entry = entries[key] || dynamicEntry(key);
    return entry ? { term: key, ...entry } : null;
  }

  function translateSentence(text) {
    return sentenceTranslations[normalize(text)] || '';
  }

